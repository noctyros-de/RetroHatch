"""Extract only technical P1 LCD geometry from the local BrickEmuPy SVG.

No shell, branding, backdrop, button graphics, firmware, or SVG renderer is bundled.
Read docs/ASSET_PROVENANCE.md before public distribution of the derived symbols.
"""
import argparse
import hashlib
import math
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "references/BrickEmuPy-main/assets/TamagotchiP1.svg"
TARGET = ROOT / "app/src/lcd_geometry.rs"
LEFT, TOP, WIDTH, HEIGHT = 173.004, 294.179, 352, 329


def contours(data):
    tokens = re.findall(r"[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?", data)
    paths, points, current = [], [], (0.0, 0.0)
    index, command = 0, None
    while index < len(tokens):
        if tokens[index].isalpha():
            command = tokens[index]
            index += 1
        assert command in ("M", "L", "H", "V", "C", "Z"), command
        if command == "Z":
            if points:
                paths.append(points)
                current = points[0]
                points = []
            command = None
            continue
        count = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6}[command]
        values = list(map(float, tokens[index:index + count]))
        assert len(values) == count
        index += count
        if command == "M":
            if points:
                paths.append(points)
            current = tuple(values)
            points = [current]
            command = "L"
        elif command == "L":
            current = tuple(values)
            points.append(current)
        elif command == "H":
            current = values[0], current[1]
            points.append(current)
        elif command == "V":
            current = current[0], values[0]
            points.append(current)
        else:
            p0, p1, p2, p3 = current, values[:2], values[2:4], values[4:]
            for sample in range(1, 33):
                t = sample / 32
                u = 1 - t
                points.append(tuple(u**3 * p0[i] + 3*u*u*t*p1[i] + 3*u*t*t*p2[i] + t**3*p3[i] for i in range(2)))
            current = tuple(p3)
    if points:
        paths.append(points)
    return paths


def filled_spans(path, y):
    intersections = []
    for points in contours(path.attrib["d"]):
        for a, b in zip(points, points[1:] + points[:1]):
            if min(a[1], b[1]) <= y < max(a[1], b[1]):
                x = a[0] + (y - a[1]) * (b[0] - a[0]) / (b[1] - a[1])
                intersections.append((x, 1 if b[1] > a[1] else -1))
    intersections.sort()
    winding, previous, spans = 0, None, []
    evenodd = path.get("fill-rule") == "evenodd"
    for x, direction in intersections:
        if previous is not None and (winding % 2 if evenodd else winding != 0):
            spans.append((previous, x))
        winding += 1 if evenodd else direction
        previous = x
    return spans


def generate():
    source = SOURCE.read_bytes()
    svg = ET.fromstring(source)
    display = next(node for node in svg.iter() if node.get("id") == "display")
    assert all("transform" not in node.attrib for node in display.iter())
    lines = [
        "// Generated by tools/extract_p1_lcd.py; display-only geometry, BrickEmuPy CC0.",
        "// Asset provenance limitations: docs/ASSET_PROVENANCE.md.",
        "// Source SHA256: " + hashlib.sha256(source).hexdigest(),
        "pub const LCD_SIZE: [f32; 2] = [352.0, 329.0];",
        "// x, y, LCD-nibble index, bit; all coordinates relative to the LCD bounds.",
        "pub const PIXELS: &[(f32, f32, u8, u8)] = &[",
    ]
    pixels, ids = [], set()
    icons = []
    for group in display:
        if group.get("id", "").startswith("col_"):
            for path in group:
                ram, bit = map(int, path.attrib["id"].split("_"))
                points = contours(path.attrib["d"])
                assert len(points) == 1
                xs, ys = zip(*points[0])
                assert abs(max(xs) - min(xs) - 10) < 0.001
                assert abs(max(ys) - min(ys) - 10) < 0.001
                x, y = min(xs) - LEFT, min(ys) - TOP
                assert (ram, bit) not in ids and 0 <= ram < 160 and 0 <= bit < 4
                ids.add((ram, bit))
                pixels.append((x, y, ram, bit))
        else:
            ram, bit = map(int, group.attrib["id"].split("_"))
            icons.append((ram, bit, group))
    assert len(pixels) == 512 and len(icons) == 8
    for x, y, ram, bit in sorted(pixels, key=lambda p: (p[1], p[0])):
        lines.append(f"    ({x:.3f}, {y:.3f}, {ram}, {bit}),")
    lines += ["];", "pub const ICON_BITS: &[(u8, u8)] = &["]
    for ram, bit, _ in icons:
        assert (ram, bit) not in ids
        lines.append(f"    ({ram}, {bit}),")
    lines += ["];", "// Horizontal one-unit coverage spans: x, y, width. Curves use 32 subdivisions.",
              "pub const ICON_SPANS: [&[(u16, u16, u16)]; 8] = ["]
    for _, _, group in icons:
        # Parse cubic curves only once per path; scan rows using cached polygons.
        paths = [(p, contours(p.attrib["d"])) for p in group]
        lines.append("    &[")
        for row in range(HEIGHT):
            coverage = [False] * WIDTH
            y = TOP + row + 0.5
            for path, polygons in paths:
                intersections = []
                for points in polygons:
                    for a, b in zip(points, points[1:] + points[:1]):
                        if min(a[1], b[1]) <= y < max(a[1], b[1]):
                            x = a[0] + (y - a[1]) * (b[0] - a[0]) / (b[1] - a[1])
                            intersections.append((x, 1 if b[1] > a[1] else -1))
                intersections.sort()
                winding, previous = 0, None
                for x, direction in intersections:
                    filled = winding % 2 if path.get("fill-rule") == "evenodd" else winding != 0
                    if previous is not None and filled:
                        start = max(0, math.ceil(previous - LEFT - 0.5))
                        end = min(WIDTH, math.ceil(x - LEFT - 0.5))
                        for column in range(start, end):
                            coverage[column] = True
                    winding += 1 if path.get("fill-rule") == "evenodd" else direction
                    previous = x
            column = 0
            while column < WIDTH:
                if not coverage[column]:
                    column += 1
                    continue
                start = column
                while column < WIDTH and coverage[column]:
                    column += 1
                lines.append(f"        ({start}, {row}, {column - start}),")
        lines.append("    ],")
    lines.append("];")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        assert TARGET.read_text(encoding="utf-8") == generated, "LCD geometry differs; regenerate and review"
        print("Verified all 512 LCD pixel mappings and eight derived icon geometries.")
    else:
        TARGET.write_text(generated, encoding="utf-8")
        print("Extracted only 512 LCD pixels and eight LCD icons; no decorative artwork.")
