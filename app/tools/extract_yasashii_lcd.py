"""Extract only Yasashii's 512 original matrix mappings; no shell or LED artwork."""
import sys
sys.dont_write_bytecode = True
import argparse
import hashlib
import xml.etree.ElementTree as ET
from pathlib import Path
from PyQt6.QtCore import QByteArray
from PyQt6.QtSvg import QSvgRenderer
from workspace_paths import references_dir
ROOT = Path(__file__).resolve().parents[2]
SOURCE = references_dir() / "BrickEmuPy-main/assets/TamagotchiYasashii.svg"
TARGET = ROOT / "app/src/yasashii_lcd_geometry.rs"
def generate():
    raw = SOURCE.read_bytes()
    display = next(n for n in ET.fromstring(raw).iter() if n.get("id") == "display")
    matrix = next(n for n in display if n.get("id") == "pixels")
    assert not any(n.get("transform") for n in matrix.iter())
    renderer = QSvgRenderer(QByteArray(raw))
    bounds = renderer.boundsOnElement("pixels")
    scale = 10.0 / 28.53
    lines = ["// Generated by tools/extract_yasashii_lcd.py from BrickEmuPy (CC0).",
             "// Electrical matrix mapping only; no shell, icons, LEDs or firmware artwork.",
             "// SVG SHA256: " + hashlib.sha256(raw).hexdigest(),
             "pub const LCD_SIZE: [f32; 2] = [351.0, 175.0];",
             "pub const PIXELS: &[(f32, f32, u8, u8)] = &["]
    seen = set()
    for node in matrix.iter():
        if not node.tag.endswith("path"): continue
        ram, bit = map(int, node.attrib["id"].split("_"))
        b = renderer.boundsOnElement(node.attrib["id"])
        assert abs(b.width() - 28.53) < .02 and abs(b.height() - 28.53) < .02
        assert (ram, bit) not in seen and ram < 160 and bit < 4
        seen.add((ram, bit))
        x, y = (b.x()-bounds.x())*scale, (b.y()-bounds.y())*scale
        assert 0 <= x < 342 and 0 <= y < 166
        lines.append(f"    ({x:.4f}, {y:.4f}, {ram}, {bit}),")
    assert len(seen) == 512
    # The six other SVG groups are GPIO LEDs outside the LCD, not LCD icons.
    assert {n.get("id") for n in display if n is not matrix} == {"160_0", "161_0", "162_0", "164_0", "165_0", "166_0"}
    return "\n".join(lines + ["];"]) + "\n"
if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = generate()
    if args.check: assert TARGET.read_text(encoding="utf-8") == data
    else: TARGET.write_text(data, encoding="utf-8")
    print("Verified 512 original Yasashii matrix mappings; six GPIO LEDs remain separate.")
