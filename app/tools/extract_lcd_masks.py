"""Extract exact display-only SVG paths through Qt, matching BrickEmuPy's renderer.

Qt is a development dependency only. No shell artwork or firmware is embedded.
Eight-times coverage masks are area-resampled at the actual display DPI in Rust.
"""
import sys
sys.dont_write_bytecode=True
import argparse,copy,hashlib,math,xml.etree.ElementTree as ET
from pathlib import Path
from PyQt6.QtCore import QByteArray,QRectF
from PyQt6.QtGui import QImage,QPainter
from PyQt6.QtSvg import QSvgRenderer
ROOT=Path(__file__).resolve().parents[2]
PROFILES=[('p1','TamagotchiP1',173.004,294.179),('genjintch','TamagotchiGenjintch',173.003,294.178),('angel','TamagotchiAngel',171.945,294.178),('morino','TamagotchiMorino',171.945,294.178),('umino','TamagotchiUmino',171.945,294.178)]
SCALE=8
def icon_source(node,box):
    x,y,w,h=box
    svg=ET.Element('svg',{'xmlns':'http://www.w3.org/2000/svg','viewBox':f'{x} {y} {w} {h}','width':str(w),'height':str(h)})
    svg.append(copy.deepcopy(node))
    return ET.tostring(svg)
def generate():
    out=['// Generated by tools/extract_lcd_masks.py from display-only SVG geometry.',
         '// Derived artwork provenance: docs/ASSET_PROVENANCE.md.',
         'pub struct Icon {pub origin:[f32;2],pub size:[usize;2],pub offset:usize,pub ram:u8,pub bit:u8}',
         "pub struct Masks {pub data: &'static [u8],pub icons:[Icon;8]}"]
    files={}
    for key,name,left,top in PROFILES:
        raw=(ROOT/f'references/BrickEmuPy-main/assets/{name}.svg').read_bytes()
        root=ET.fromstring(raw);display=next(n for n in root.iter() if n.get('id')=='display')
        assert not any(n.get('transform') for n in display.iter())
        renderer=QSvgRenderer(QByteArray(raw));assert renderer.isValid()
        groups=[g for g in display if not g.get('id','').startswith('col_')];assert len(groups)==8
        data=bytearray();entries=[]
        for node in groups:
            ram,bit=map(int,node.get('id').split('_'))
            b=renderer.boundsOnElement(node.get('id'))
            x=math.floor((b.x()-left-2)*SCALE)/SCALE+left;y=math.floor((b.y()-top-2)*SCALE)/SCALE+top
            w=math.ceil((b.right()+2-x)*SCALE);h=math.ceil((b.bottom()+2-y)*SCALE)
            image=QImage(w,h,QImage.Format.Format_ARGB32_Premultiplied);image.fill(0)
            original=QSvgRenderer(QByteArray(icon_source(node,(x,y,w/SCALE,h/SCALE))));assert original.isValid()
            painter=QPainter(image);original.render(painter,QRectF(0,0,w,h));painter.end()
            alpha=image.convertToFormat(QImage.Format.Format_Alpha8)
            pixels=alpha.constBits().asstring(alpha.sizeInBytes());stride=alpha.bytesPerLine()
            offset=len(data)
            for row in range(h):data.extend(pixels[row*stride:row*stride+w])
            entries.append(f'Icon {{origin:[{x-left:.6f},{y-top:.6f}],size:[{w},{h}],offset:{offset},ram:{ram},bit:{bit}}}')
        files[ROOT/f'app/assets/lcd/{key}.alpha']=bytes(data)
        out += [f'// {name} SVG SHA256: {hashlib.sha256(raw).hexdigest()}',f'pub static {key.upper()}:Masks=Masks{{data:include_bytes!("../assets/lcd/{key}.alpha"),icons:[',*['    '+e+',' for e in entries],']};']
    files[ROOT/'app/src/lcd_masks.rs']=('\n'.join(out)+'\n').encode()
    return files
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    for path,data in generate().items():
        if args.check:assert path.read_bytes()==data,f'Coverage mask differs: {path}'
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    print('Verified exact Qt SVG coverage masks for five displays.' if args.check else 'Generated display-only Qt coverage masks for five displays.')
